# Build a tool-neutral ("portable") variant of each skill under skills/ and deploy it to
# the skill folders read by other agent CLIs (Codex, dsh, Kimi, ZCode).
#
# skills/ stays the only source of truth. The portable variant is GENERATED:
#   1. copy skills/<name>/ to a temp build folder
#   2. overlay files from variants/portable/<name>/ (whole-file replacements)
#   3. apply the literal/regex rules in variants/portable/replacements.json
#      - every rule must match, otherwise the build fails (so edits to skills/ cannot
#        silently drop an adaptation)
#      - no "forbidden" token (Claude Code specific tool names) may survive
#   4. copy the result to each target root
#
# A target copy that was NOT generated by this script (no marker in its SKILL.md) is
# backed up before it is overwritten.
#
# This file must stay ASCII-only: Windows PowerShell 5.1 reads BOM-less scripts as ANSI.
# All non-ASCII text lives in replacements.json, which is read explicitly as UTF-8.
#
# Usage:
#   ./scripts/deploy-skill-portable.ps1                 # build + deploy to default targets
#   ./scripts/deploy-skill-portable.ps1 -BuildOnly      # build only, print the build folder
#   ./scripts/deploy-skill-portable.ps1 -Targets D:\x   # deploy to other skill roots

param(
    [string[]]$Targets = @(
        (Join-Path $env:USERPROFILE ".agents\skills"),   # read by Codex, dsh, Kimi
        (Join-Path $env:USERPROFILE ".zcode\skills")     # read by ZCode
    ),
    [string]$BackupRoot = (Join-Path $env:USERPROFILE ".agents\backups"),
    [switch]$BuildOnly
)

$ErrorActionPreference = "Stop"

$repo       = Split-Path $PSScriptRoot -Parent
$repoSkills = Join-Path $repo "skills"
$variant    = Join-Path $repo "variants\portable"
$marker     = "deploy-skill-portable.ps1"
$utf8NoBom  = New-Object System.Text.UTF8Encoding($false)

$config = Get-Content (Join-Path $variant "replacements.json") -Raw -Encoding UTF8 | ConvertFrom-Json

Get-ChildItem -Directory $repoSkills | ForEach-Object {
    $name  = $_.Name
    $build = Join-Path ([System.IO.Path]::GetTempPath()) ("portable-skill-" + $name + "-" + [guid]::NewGuid().ToString("N"))

    # 1. copy the source
    Copy-Item -Recurse -Force $_.FullName $build

    # 2. overlay whole-file replacements
    $overlay = Join-Path $variant $name
    if (Test-Path $overlay) {
        Copy-Item -Recurse -Force (Join-Path $overlay "*") $build
    }

    # 3. apply rules; each one must match
    $applied = 0
    foreach ($rule in $config.rules) {
        if ($rule.skill -ne $name) { continue }
        $path = Join-Path $build $rule.file
        if (-not (Test-Path $path)) { throw "Rule targets a missing file: $($rule.file)" }
        $text = [System.IO.File]::ReadAllText($path, $utf8NoBom)
        $nl   = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
        $rep  = $rule.replace.Replace("{NL}", $nl)
        if ($rule.regex) {
            if ([regex]::Matches($text, $rule.find).Count -lt 1) {
                throw "Regex rule did not match in $($rule.file): $($rule.find)"
            }
            $text = [regex]::Replace($text, $rule.find, $rep)
        } else {
            if (-not $text.Contains($rule.find)) {
                throw "Rule did not match in $($rule.file): $($rule.find)"
            }
            $text = $text.Replace($rule.find, $rep)
        }
        [System.IO.File]::WriteAllText($path, $text, $utf8NoBom)
        $applied++
    }

    # no Claude Code specific tool name may survive, and no file may start with a BOM
    Get-ChildItem -Recurse -File $build -Filter *.md | ForEach-Object {
        $bytes = [System.IO.File]::ReadAllBytes($_.FullName)
        if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF) {
            throw "BOM found in $($_.Name)"
        }
        $t = [System.IO.File]::ReadAllText($_.FullName, $utf8NoBom)
        foreach ($tok in $config.forbidden) {
            if ($t.Contains($tok)) { throw "Forbidden token '$tok' left in $($_.Name)" }
        }
    }
    $skillText = [System.IO.File]::ReadAllText((Join-Path $build "SKILL.md"), $utf8NoBom)
    if (-not $skillText.Contains($marker)) { throw "Marker missing from built SKILL.md" }
    if (-not $skillText.StartsWith("---")) { throw "Built SKILL.md does not start with frontmatter" }

    Write-Host "Built portable $name ($applied rules applied)"

    if ($BuildOnly) {
        Write-Host "Build folder: $build"
        return
    }

    # 4. deploy
    foreach ($root in $Targets) {
        if (-not (Test-Path $root)) {
            Write-Host "Skipped $root (folder does not exist)"
            continue
        }
        $dst = Join-Path $root $name
        if (Test-Path $dst) {
            $dstSkill  = Join-Path $dst "SKILL.md"
            $generated = (Test-Path $dstSkill) -and ([System.IO.File]::ReadAllText($dstSkill, $utf8NoBom).Contains($marker))
            if (-not $generated) {
                $owner  = (Split-Path (Split-Path $root -Parent) -Leaf).TrimStart(".")
                $backup = Join-Path $BackupRoot ($name + "-" + $owner + "-" + (Get-Date -Format "yyyyMMdd-HHmmss"))
                New-Item -ItemType Directory -Force (Split-Path $backup -Parent) | Out-Null
                Copy-Item -Recurse -Force $dst $backup
                Write-Host "Backed up hand-edited copy -> $backup"
            }
            Remove-Item -Recurse -Force $dst
        }
        Copy-Item -Recurse -Force $build $dst
        Write-Host "Deployed portable $name -> $dst"
    }

    Remove-Item -Recurse -Force $build
}
